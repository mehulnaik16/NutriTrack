/**
 * Standard home recipes for common Indian dishes the catalog was missing.
 *
 * `ing` is raw grams by ingredient code (IFCT 2017, or a REFERENCE code in
 * recipe-calc.mjs). Water and salt are left out: they carry no macros, and the
 * water a dish keeps or loses is what `yield` (the cooked weight, g) records.
 * Fried food lists only the oil it absorbs. `piece_g` is one typical piece.
 *
 * Codes used most: A015 rice, A019 atta, A018 maida, A022 sooji, B001 chana
 * dal/besan, B003 urad dal, B010 moong dal, B021 toor dal, B002 chickpea,
 * F006 potato, G017 onion, D075 tomato, T005 groundnut oil, T013 ghee,
 * L002 cow milk, L001 buffalo milk, L003 paneer, L004 khoa, H007 coconut.
 */
const r = (name, grup, ing, yieldG, piece_g, note) => ({
  name,
  grup,
  ing,
  yield: yieldG,
  ...(piece_g ? { piece_g } : {}),
  ...(note ? { note } : {}),
});

