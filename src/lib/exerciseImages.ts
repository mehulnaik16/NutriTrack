/**
 * Normalizes an exercise name for robust dictionary lookup:
 * - Lowercase
 * - Strips punctuation / hyphens
 * - Collapses extra spaces
 */
export function normalizeExerciseKey(name: string): string {
  if (!name) return "";
  return name
    .toLowerCase()
    .replace(/[-_]/g, " ")
    .replace(/[^\w\s]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

